#!/usr/bin/env python3
"""Build the checked-in, single-window SQLQueryStress pair. No database access.

Numbered scenarios remain the source for procedure calls and eligibility rules.
Operators use the generated SQL directly; this is a maintainer-only command.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORKLOAD = ROOT / 'workload'
GROUPS = json.loads((WORKLOAD / 'manifest.json').read_text())
DEFAULT = {'name': '.', 'share': 100, 'mappings': {'InputTargets': 'TargetsJson'}}
# Output order/types of the numbered selectors; checked against live JSON decoding.
SHAPES = {
    '01': [('QuestionId', 'int')],
    '03': [('UserId', 'int')],
    '04': [('PostId', 'int'), ('UserId', 'int'), ('TagName', 'nvarchar(150)')],
    '05': [('QuestionId', 'int'), ('UserId', 'int')],
    '06': [('PostId', 'int'), ('PostTypeId', 'int'), ('UserId', 'int')],
    '07': [('QuestionId', 'int'), ('UserId', 'int'), ('TagName', 'nvarchar(150)')],
    '08': [('PostId', 'int'), ('PostTypeId', 'int'), ('UserId', 'int'),
           ('Tag1', 'nvarchar(150)'), ('Tag2', 'nvarchar(150)')],
    '09': [('QuestionId', 'int'), ('AnswerId', 'int'), ('UserId', 'int'), ('RelatedQuestionId', 'int')],
    '11': [('QuestionId', 'int'), ('UserId', 'int')],
    '12': [('QuestionId', 'int'), ('TagName', 'nvarchar(150)'), ('SearchText', 'nvarchar(250)'),
           ('FromDate', 'datetime'), ('ToDate', 'datetime'), ('BadgeName', 'nvarchar(40)')],
}


def decode(group):
    """Shared typed projection for the main batch and read-only round-trip checks."""
    number = group['name'][:2]
    columns = ',\n   '.join(f"[{col}] {typ} 'strict $.{col}'" for col, typ in SHAPES[number])
    return f"OPENJSON(@InputTargets, 'strict $.\"{group['name']}\"')\n  WITH ({columns})"


def build():
    baseline = [g for g in GROUPS if g['share'] > 0]
    assert sum(g['share'] for g in baseline) == 100
    header = '-- Generated by tests/integration/package_workload.py; edit numbered scenarios, then regenerate.\n'
    calls = [header, '-- Paste this entire batch into ONE SQLQueryStress window. No GO.\n',
             '-- Parameter Substitution: map TargetsJson to @InputTargets (the only input).\n',
             '-- Each invocation chooses one operation; writes commit to the selected database.\n',
             'SET NOCOUNT ON;\n',
             "IF COALESCE(ISJSON(@InputTargets),0)<>1 THROW 51102,'Map TargetsJson to InputTargets using workload/parameters.sql.',1;\n",
             'DECLARE @Operation int=ABS(CONVERT(bigint,CHECKSUM(NEWID()))) % 100;\n']
    upper = 0
    for group in baseline:
        number = group['name'][:2]
        upper += group['share']
        keyword = 'IF' if upper == group['share'] else 'ELSE IF'
        calls.append(f"\n{keyword} @Operation<{upper} -- {group['share']}%: {group['name']}\nBEGIN\n")
        if group['mappings']:
            types = dict(SHAPES[number])
            declarations = ', '.join(f'@g{number}_{var} {types[col]}' for var, col in group['mappings'].items())
            assignments = ', '.join(f'@g{number}_{var}=[{col}]' for var, col in group['mappings'].items())
            calls.append(f' DECLARE {declarations};\n SELECT {assignments}\n FROM {decode(group)};\n')
        body = (WORKLOAD / group['name'] / 'calls.sql').read_text().split('SET NOCOUNT ON;\n', 1)[1]
        # Rename declared variables and substituted inputs, never EXEC's named arguments.
        variables = set(re.findall(r'DECLARE\s+(@\w+)', body, re.I)) | {'@'+v for v in group['mappings']}
        body = re.sub(r'@\w+', lambda m: '@g'+number+'_'+m[0][1:] if m[0] in variables else m[0], body)
        # A named EXEC argument can share a local variable's name (e.g. @Body=@Body).
        lines = []
        for line in body.splitlines():
            if 'EXEC dbo.' in line:
                prefix, execution = line.split('EXEC dbo.', 1)
                execution = re.sub(r'@g'+number+r'_(\w+)=', r'@\1=', execution)
                line = prefix+'EXEC dbo.'+execution
            lines.append((' '+line).rstrip())
        calls.append('\n'.join(lines)+'\nEND\n')
    calls.append(';\n')

    # All selectors share one bounded Posts/Users sample, avoiding twelve independent scans.
    source = (WORKLOAD / '01-pages/parameters.sql').read_text()
    shared = source[source.index('SET NOCOUNT ON;'):source.index('SELECT TOP(512) Id AS QuestionId')]
    parameters = [header, '-- Paste into Parameter Substitution, Get Columns, map TargetsJson to @InputTargets.\n',
                  '-- Read-only setup: bounded local table variables disappear when this batch finishes.\n', shared]
    tagged = (WORKLOAD / '07-content/parameters.sql').read_text().split(shared, 1)[1]
    tag_setup = tagged[:tagged.index(';WITH P AS')]
    parameters.append(tag_setup)
    joins, objects = [], []
    for group in baseline:
        if not group['mappings']:
            continue
        number = group['name'][:2]
        columns = SHAPES[number]
        source = (WORKLOAD / group['name'] / 'parameters.sql').read_text()
        assert shared in source, group['name']
        selection = source.split(shared, 1)[1]
        if selection.startswith(tag_setup):
            selection = selection[len(tag_setup):]
        table = '@G'+number
        definitions = ','.join(f'[{col}] {typ} NOT NULL' for col, typ in columns)
        names = ','.join('['+col+']' for col, _ in columns)
        parameters.append(f"\n-- {group['name']}: keep each eligible tuple together.\nDECLARE {table} table(Rn int IDENTITY(1,1) PRIMARY KEY,{definitions});\n")
        # The output SELECT follows any CTE; nested TOP queries are never insertion targets.
        selection, count = re.subn(r'^SELECT TOP\(', f'INSERT {table}({names})\nSELECT TOP(', selection, count=1, flags=re.M)
        assert count == 1, group['name']
        parameters.append(selection)
        parameters.append(f"DECLARE @Count{number} int=(SELECT COUNT(*) FROM {table});\nIF @Count{number}=0 THROW 51103,'No eligible rows for {group['name']}; rerun parameter selection before starting.',1;\n")
        fields = ','.join(f'g{number}.[{col}]' for col, _ in columns)
        objects.append(f" JSON_QUERY((SELECT {fields} FOR JSON PATH,WITHOUT_ARRAY_WRAPPER)) AS [{group['name']}]")
        joins.append(f'JOIN {table} g{number} ON g{number}.Rn=1+(n.Rn-1)%NULLIF(@Count{number},0)')
    parameters.extend(['\n-- Each cached row carries a target tuple for every branch; hot targets cycle over eight rows.\n',
                       ';WITH Numbers AS (SELECT TOP(512) ROW_NUMBER() OVER(ORDER BY Id) AS Rn FROM @Posts)\n',
                       'SELECT (SELECT\n', ',\n'.join(objects), '\n FOR JSON PATH,WITHOUT_ARRAY_WRAPPER) AS TargetsJson\n',
                       'FROM Numbers n\n', '\n'.join(joins), '\nORDER BY n.Rn;\n'])
    return {'calls.sql': ''.join(calls), 'parameters.sql': ''.join(parameters)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated SQL is out of date')
    args = parser.parse_args()
    for filename, sql in build().items():
        path = WORKLOAD / filename
        if args.check:
            assert path.read_text() == sql, f'Regenerate {path}'
        else:
            path.write_text(sql)
    print('Single-window package is current.' if args.check else 'Wrote single-window SQL pair.')


if __name__ == '__main__':
    main()
